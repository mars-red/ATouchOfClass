"""Generate exact tapered window-box meshes and all vanilla wood resources.

NeoForge's built-in OBJ loader preserves the trapezoidal panels from the
approved preview; no custom renderer or copied vanilla textures are needed.
"""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'src/main/resources/assets/atouchofclass'
DATA = ROOT / 'src/main/resources/data/atouchofclass'


def write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2) + '\n', encoding='utf-8')


def geometry(left, right):
    """SOUTH-facing, back at Z=0. Joined edges have no taper or cap."""
    xl, xr = (0 if left else 1), (16 if right else 15)
    il, ir = (0 if left else 1), (16 if right else 15)
    bl, br = (0 if left else 1.875), (16 if right else 14.125)
    ot = [(0,16,0),(16,16,0),(16,16,10),(0,16,10)]
    ob = [(xl,8,0),(xr,8,0),(xr,8,9),(xl,8,9)]
    it = [(il,16,1),(ir,16,1),(ir,16,9),(il,16,9)]
    ib = [(bl,9,1),(br,9,1),(br,9,8.125),(bl,9,8.125)]
    faces = []
    for i in range(4):
        if (i == 1 and right) or (i == 3 and left):
            continue
        j = (i+1)%4
        mode = 'side' if i in (1,3) else 'front'
        # Outward winding, including the inward-facing inside walls.
        faces.extend([([ob[j],ob[i],ot[i],ot[j]], 'wood', mode),
                      ([ib[i],ib[j],it[j],it[i]], 'wood', mode),
                      ([ot[j],ot[i],it[i],it[j]], 'wood', 'top')])
    faces.append((ob, 'wood', 'top'))  # underside faces down
    dl, dr = (0 if left else 1.25), (16 if right else 14.75)
    faces.append(([(dl,14,1),(dl,14,8.75),(dr,14,8.75),(dr,14,1)], 'dirt', 'top'))
    return faces


def export_obj(left, right, part):
    lines = ['# Generated by tools/generate_window_boxes.py',
             'mtllib atouchofclass:models/block/window_box.mtl', 'g window_box']
    count = 0
    for vertices, material, mode in geometry(left, right):
        lines.append('usemtl ' + material)
        for x,y,z in vertices:
            lines.append(f'v {x/16:.8f} {y/16:.8f} {z/16:.8f}')
        for x,y,z in vertices:
            u,v = (x,z+6) if mode == 'top' else ((z+6,16-y) if mode == 'side' else (x,16-y))
            # Rotate the stripped side-grain texture clockwise by 90 degrees.
            if material == 'wood':
                u,v = v,16-u
            lines.append(f'vt {u/16:.8f} {v/16:.8f}')
        lines.append('f ' + ' '.join(f'{count+i}/{count+i}' for i in range(1,5)))
        count += 4
    (ASSETS / f'models/block/window_box_{part}.obj').write_text('\n'.join(lines)+'\n', encoding='utf-8')


def main():
    woods = re.findall(r'new Definition\("([a-z_]+)"', (ROOT / 'src/main/java/com/digitaldownpour/atouchofclass/WindowBoxVariants.java').read_text())
    assert woods and len(woods) == len(set(woods))
    parts = [(False,False,'single'),(False,True,'left'),(True,True,'middle'),(True,False,'right')]
    (ASSETS / 'models/block').mkdir(parents=True, exist_ok=True)
    (ASSETS / 'models/block/window_box.mtl').write_text(
        'newmtl wood\nKd 1 1 1\nmap_Kd #wood\nnewmtl dirt\nKd 1 1 1\nmap_Kd #dirt\n', encoding='utf-8')
    for left,right,part in parts:
        export_obj(left,right,part)
    lang_path = ASSETS / 'lang/en_us.json'
    lang = json.loads(lang_path.read_text(encoding='utf-8'))
    axe_path = ROOT / 'src/main/resources/data/minecraft/tags/block/mineable/axe.json'
    axe = json.loads(axe_path.read_text(encoding='utf-8'))
    for wood in woods:
        name = f'{wood}_window_box'
        identifier = f'atouchofclass:{name}'
        texture = ('stripped_bamboo_block' if wood == 'bamboo' else
                   f'stripped_{wood}_stem' if wood in ('crimson','warped') else f'stripped_{wood}_log')
        variants = {}
        for left,right,part in parts:
            write(ASSETS / f'models/block/{name}_{part}.json', {
                'parent':'minecraft:block/block', 'loader':'neoforge:obj',
                'model':f'atouchofclass:models/block/window_box_{part}.obj',
                'automatic_culling':False, 'flip_v':False, 'ambientocclusion':False,
                'textures':{'particle':f'minecraft:block/{texture}', 'wood':f'minecraft:block/{texture}', 'dirt':'minecraft:block/dirt'}})
            for facing,rotation in [('south',0),('west',90),('north',180),('east',270)]:
                variants[f'facing={facing},joined_left={str(left).lower()},joined_right={str(right).lower()}'] = {
                    'model':f'atouchofclass:block/{name}_{part}', 'y':rotation}
        write(ASSETS / f'blockstates/{name}.json', {'variants':variants})
        write(ASSETS / f'models/item/{name}.json', {'parent':f'atouchofclass:block/{name}_single'})
        write(ASSETS / f'items/{name}.json', {'model':{'type':'minecraft:model','model':f'atouchofclass:item/{name}'}})
        write(DATA / f'recipe/{name}.json', {'type':'minecraft:crafting_shaped','category':'building',
            'pattern':['WWW','DDD','WWW'],'key':{'W':f'minecraft:{wood}_planks','D':'minecraft:dirt'},
            'result':{'id':identifier,'count':6}})
        write(DATA / f'advancement/recipes/building_blocks/{name}.json', {
            'parent':'minecraft:recipes/root','criteria':{
                'has_material':{'trigger':'minecraft:inventory_changed','conditions':{'items':[{'items':f'minecraft:{wood}_planks'}]}},
                'has_the_recipe':{'trigger':'minecraft:recipe_unlocked','conditions':{'recipes':[identifier]}}},
            'requirements':[['has_material','has_the_recipe']], 'rewards':{'recipes':[identifier]}})
        write(DATA / f'loot_table/blocks/{name}.json', {'type':'minecraft:block','pools':[{
            'rolls':1,'conditions':[{'condition':'minecraft:survives_explosion'}],
            'entries':[{'type':'minecraft:item','name':identifier}]}]})
        lang[f'block.atouchofclass.{name}'] = wood.replace('_',' ').title()+' Window Box'
        if identifier not in axe['values']: axe['values'].append(identifier)
    # Retain the existing files' formatting and ordering outside the new entries.
    original = lang_path.read_text(encoding='utf-8')
    missing = {k:v for k,v in lang.items() if k not in json.loads(original)}
    if missing:
        lang_path.write_text(original.rstrip().removesuffix('}').rstrip()+',\n'+
                            ',\n'.join('    '+json.dumps(k)+': '+json.dumps(v) for k,v in missing.items())+'\n}\n', encoding='utf-8')
    original = axe_path.read_text(encoding='utf-8')
    old = json.loads(original)['values']
    additions = [v for v in axe['values'] if v not in old]
    if additions:
        index = original.rfind(']')
        original = original[:index].rstrip()+',\n'+',\n'.join('    '+json.dumps(v) for v in additions)+'\n  '+original[index:]
        axe_path.write_text(original, encoding='utf-8')
    print(f'Generated {len(woods)} window boxes, 16 states each, four shared tapered meshes, items, recipes, unlocks and loot.')


if __name__ == '__main__':
    main()
