"""Compact, double-sided vanilla-textured bunch models, planter tag and crafting data."""
from pathlib import Path
import json
import math
import re
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
ASSETS=ROOT/'src/main/resources/assets/atouchofclass'
DATA=ROOT/'src/main/resources/data/atouchofclass'
VANILLA=ROOT/'build/neoForm/neoFormJoined26.3-1/steps/transformSource/transformed/assets/minecraft/textures/block'

def write(path,value):
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(value,indent=2)+'\n',encoding='utf-8')

def bounds(texture):
    return Image.open(VANILLA/(texture+'.png')).convert('RGBA').getbbox()

def crossed(texture,x,z,y,height,width,angle=40):
    u0,v0,u1,v1=bounds(texture)
    uv=[(u0,v1),(u1,v1),(u1,v0),(u0,v0)]
    result=[]
    for a in (angle,angle+90):
        a=math.radians(a);dx=math.cos(a)*width/2;dz=math.sin(a)*width/2
        v=[(x-dx,y,z-dz),(x+dx,y,z+dz),(x+dx,y+height,z+dz),(x-dx,y+height,z-dz)]
        result.append((v,uv,texture,True))
    return result

def geometry(flower,family):
    faces=[]
    if family=='small':
        heights=[[7.8,8.7,8.0,8.2],[8.5,9.0,8.4,8.6],[7.5,7.8,7.2,7.7]]
        u0,v0,u1,v1=bounds(flower)
        for row,z in enumerate([2.8,5,7.2]):
            for col,x in enumerate([1.7,5.9,10.1,14.3]):
                x+=[.12,-.2,.08][(row+col)%3]
                h=heights[row][col];width=min(8.1,h*(u1-u0)/(v1-v0))
                faces+=crossed(flower,x,z,0,h,width,35+row*9+col*5)
    elif family=='shrub':
        heights=[[10.5,11.8,11,11.2],[11.2,12,11.4,11.8],[10.2,11,10.4,10.8]]
        for row,z in enumerate([2.8,5,7.2]):
            for col,x in enumerate([1.7,5.9,10.1,14.3]):
                angle=35+row*9+col*5
                faces+=crossed(flower+'_bottom',x,z,0,3.5,3.2,angle)
                faces+=crossed(flower+'_top',x,z,3.5,heights[row][col]-3.5,5.1,angle)
    elif family=='sunflower':
        for row,z in enumerate([3,6.8]):
            for col,x in enumerate([1.7,5.9,10.1,14.3]):
                faces+=crossed('sunflower_bottom',x,z,0,5.2,4.5,40+row*8+col*5)
        for i,(x,z,h) in enumerate([(1.8,4.1,12.1),(4.8,6.2,13.6),(8,3.5,12.8),(11.2,6,14),(14.3,4.5,12.4)]):
            faces+=crossed('sunflower_top',x,z,4.2,h-7.3,3.8,35+i*7)
            width=4.4 if i%2==0 else 4.9
            v=[(x-width/2,h-width,z+.05),(x+width/2,h-width,z+.05),(x+width/2,h,z+.05),(x-width/2,h,z+.05)]
            for texture,vertices in [('sunflower_front',v),('sunflower_back',list(reversed(v)))]:
                u0,v0,u1,v1=bounds(texture)
                uv=[(u0,v1),(u1,v1),(u1,v0),(u0,v0)]
                faces.append((vertices,uv,texture,False))
    elif family=='pitcher':
        for row,z in enumerate([3,6.8]):
            for col,x in enumerate([1.7,5.9,10.1,14.3]):
                faces+=crossed('pitcher_crop_bottom_stage_4',x,z,0,4.5,4.4,40+col*7)
        for i,(x,z,h) in enumerate([(1.8,4,10.5),(4.8,6.2,11.7),(8,3.5,11),(11.2,6,12),(14.3,4.5,10.8)]):
            faces+=crossed('pitcher_crop_top_stage_4',x,z,3.5,h-3.5,5.4,35+i*7)
    elif family=='mat':
        for row,z in enumerate([2.5,5,7.5]):
            for col,x in enumerate([1.7,5.9,10.1,14.3]):
                h=3.5+((row+col)%3)*.75
                faces+=crossed(flower+'_stem',x,z,0,h,2.5,35+col*7)
                # The native flowerbed atlas supplies a different cluster in each quadrant.
                u=(col%2)*8;v=(row%2)*8
                vertices=[(x-2.3,h,z-1.5),(x-2.3,h,z+1.5),(x+2.3,h,z+1.5),(x+2.3,h,z-1.5)]
                faces.append((vertices,[(u,v),(u,v+8),(u+8,v+8),(u+8,v)],flower,True))
    else: raise ValueError(family)
    return faces

def export(name,faces,planted):
    materials=sorted({face[2] for face in faces})
    lines=['# Generated by tools/generate_flower_bunches.py',f'mtllib atouchofclass:models/block/{name}.mtl','g bunch']
    index=0
    for vertices,uv,texture,double in faces:
        lines.append('usemtl '+texture)
        for x,y,z in vertices:
            lines.append(f'v {x/16:.8f} {(y-(2 if planted else 0))/16:.8f} {z/16:.8f}')
        for u,v in uv:
            lines.append(f'vt {min(.99999,max(.00001,u/16)):.8f} {min(.99999,max(.00001,v/16)):.8f}')
        ids=[f'{index+i}/{index+i}' for i in range(1,5)]
        lines.append('f '+' '.join(ids))
        if double:lines.append('f '+' '.join(reversed(ids)))
        index+=4
    suffix='planted' if planted else 'inventory'
    (ASSETS/f'models/block/{name}_{suffix}.obj').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    mtl=[]
    for mat in materials:
        color='0.48 0.69 0.27' if mat.endswith('_stem') and mat.startswith(('pink_petals','wildflowers')) else '1 1 1'
        mtl.extend([f'newmtl {mat}',f'Kd {color}',f'map_Kd #{mat}'])
    (ASSETS/f'models/block/{name}.mtl').write_text('\n'.join(mtl)+'\n',encoding='utf-8')
    particle=next((m for m in materials if 'stem' not in m),materials[0])
    textures={m:'minecraft:block/'+m for m in materials}
    textures['particle']='minecraft:block/'+particle
    model={'parent':'minecraft:block/block','loader':'neoforge:obj',
           'model':f'atouchofclass:models/block/{name}_{suffix}.obj','automatic_culling':False,
           'flip_v':False,'shade_quads':False,'ambientocclusion':False,'textures':textures}
    if not planted:
        model['display']={'gui':{'rotation':[30,225,0],'translation':[0,2,0],'scale':[.8,.8,.8]},
                          'fixed':{'rotation':[0,180,0],'translation':[0,2,0],'scale':[.8,.8,.8]}}
    write(ASSETS/f'models/block/{name}_{suffix}.json',model)

def main():
    definitions=re.findall(r'new Definition\("([a-z_]+)", Blocks\.[A-Z_]+, "([a-z]+)"',
            (ROOT/'src/main/java/com/digitaldownpour/atouchofclass/FlowerBunchVariants.java').read_text())
    assert len(definitions)==25 and len({d[0] for d in definitions})==25
    lang_path=ASSETS/'lang/en_us.json';original=lang_path.read_text(encoding='utf-8');lang=json.loads(original);labels={}
    for flower,family in definitions:
        name=flower+'_bunch';identifier='atouchofclass:'+name
        faces=geometry(flower,family)
        export(name,faces,True);export(name,faces,False)
        write(ASSETS/f'blockstates/{name}.json',{'variants':{f'facing={facing}':{'model':f'atouchofclass:block/{name}_planted','y':rot}
                    for facing,rot in [('south',0),('west',90),('north',180),('east',270)]}})
        write(ASSETS/f'models/item/{name}.json',{'parent':f'atouchofclass:block/{name}_inventory'})
        write(ASSETS/f'items/{name}.json',{'model':{'type':'minecraft:model','model':f'atouchofclass:item/{name}'}})
        write(DATA/f'recipe/{name}.json',{'type':'minecraft:crafting_shaped','category':'misc','pattern':['FF','FF'],
                 'key':{'F':'minecraft:'+flower},'result':{'id':identifier,'count':1}})
        write(DATA/f'advancement/recipes/decorations/{name}.json',{'parent':'minecraft:recipes/root','criteria':{
            'has_flower':{'trigger':'minecraft:inventory_changed','conditions':{'items':[{'items':'minecraft:'+flower}]}},
            'has_the_recipe':{'trigger':'minecraft:recipe_unlocked','conditions':{'recipes':[identifier]}}},
            'requirements':[['has_flower','has_the_recipe']],'rewards':{'recipes':[identifier]}})
        write(DATA/f'loot_table/blocks/{name}.json',{'type':'minecraft:block','pools':[{'rolls':1,
            'conditions':[{'condition':'minecraft:survives_explosion'}],'entries':[{'type':'minecraft:item','name':identifier}]}]})
        label='block.atouchofclass.'+name
        if label not in lang:labels[label]=flower.replace('_',' ').title()+' Bunch'
    if labels:
        lang_path.write_text(original.rstrip().removesuffix('}').rstrip()+',\n'+
                ',\n'.join('    '+json.dumps(k)+': '+json.dumps(v) for k,v in labels.items())+'\n}\n',encoding='utf-8')
    woods=re.findall(r'new Definition\("([a-z_]+)"',(ROOT/'src/main/java/com/digitaldownpour/atouchofclass/WindowBoxVariants.java').read_text())
    write(DATA/'tags/block/flower_bunch_planters.json',{'replace':False,'values':['atouchofclass:'+w+'_window_box' for w in woods]})
    print('Generated 25 bunches: planted/inventory meshes, four facings, recipes, unlocks, loot, planter support tag.')

if __name__=='__main__':main()
