$ErrorActionPreference='Stop'
$root=Split-Path $PSScriptRoot -Parent
$assets="$root/src/main/resources/assets/atouchofclass"
# Inset the shaft so the base and cap project on all four sides. Four fixed
# raised panels share the 12.75-unit centerlines; the outward pair reaches
# the cell boundaries. Their 4.5x8 faces frame the rail's 3x4 cross-section.
$boxes=@(
    @(9.5,0,9.5,16,1.5,16),
    @(10,1.5,10,15.5,3,15.5),
    @(10.5,3,10.5,15,19,15),
    @(9.5,19,9.5,16,20,16),
    @(10,20,10,15.5,22,15.5),
    @(15,10,10.5,16,18,15),
    @(10.5,10,15,15,18,16),
    @(9.5,10,10.5,10.5,18,15),
    @(10.5,10,9.5,15,18,10.5)
)
$tables=@()
foreach($part in @('lower','upper','item')) {
    $elements=@()
    $offset=if($part -eq 'upper'){16}else{0}
    $limit=if($part -eq 'lower'){16}else{22}
    foreach($b in $boxes) {
        $y0=[Math]::Max([double]$offset,[double]$b[1]);$y1=[Math]::Min([double]$limit,[double]$b[4])
        if($y1 -le $y0){continue}
        $faces=@{}
        foreach($side in @('north','south','east','west','up','down')) {
            if(($part -eq 'lower' -and $side -eq 'up' -and $y1 -eq 16) -or ($part -eq 'upper' -and $side -eq 'down' -and $y0 -eq 16)){continue}
            $faces[$side]=@{texture='#wood'}
        }
        $elements+=@{from=@($b[0],($y0-$offset),$b[2]);to=@($b[3],($y1-$offset),$b[5]);faces=$faces}
    }
    $model=@{parent='minecraft:block/block';textures=@{wood='minecraft:block/stripped_oak_log';particle='minecraft:block/stripped_oak_log'};elements=$elements}
    if($part -eq 'item') {
        # Reuse the placed halves' local UVs before lifting the upper geometry.
        # Implicit UVs on a 22-unit model extend outside the texture atlas sprite.
        $itemElements=@()
        foreach($half in @('lower','upper')) {
            $placed=Get-Content "$assets/models/block/oak_newel_post_$half.json" -Raw | ConvertFrom-Json
            foreach($e in $placed.elements) {
                $a=$e.from;$b=$e.to
                foreach($face in $e.faces.PSObject.Properties) {
                    $uv=switch($face.Name) {
                        'down' {@($a[0],(16-$b[2]),$b[0],(16-$a[2]))}
                        'up' {@($a[0],$a[2],$b[0],$b[2])}
                        'north' {@((16-$b[0]),(16-$b[1]),(16-$a[0]),(16-$a[1]))}
                        'south' {@($a[0],(16-$b[1]),$b[0],(16-$a[1]))}
                        'west' {@($a[2],(16-$b[1]),$b[2],(16-$a[1]))}
                        'east' {@((16-$b[2]),(16-$b[1]),(16-$a[2]),(16-$a[1]))}
                    }
                    $face.Value | Add-Member -NotePropertyName uv -NotePropertyValue $uv
                }
                if($half -eq 'upper') {$e.from[1]+=16;$e.to[1]+=16}
                $itemElements+=$e
            }
        }
        $model.elements=$itemElements
        $model.display=@{gui=@{rotation=@(30,225,0);translation=@(3.695,-1.332,0);scale=@(0.55,0.55,0.55)}}
        $model | ConvertTo-Json -Depth 20 | Set-Content "$assets/models/item/oak_newel_post.json"
    } else {
        $model | ConvertTo-Json -Depth 20 | Set-Content "$assets/models/block/oak_newel_post_$part.json"
        $tables+='        {'+(($elements | ForEach-Object {'{'+(($_.from+$_.to)-join ',')+'}'})-join ',')+'}'
    }
}
$variants=@{};$turn=0
foreach($facing in @('north','east','south','west')) {
    foreach($half in @('lower','upper')) {$variants["facing=$facing,half=$half"]=@{model="atouchofclass:block/oak_newel_post_$half";y=$turn;uvlock=$true}}
    $turn+=90
}
@{variants=$variants}|ConvertTo-Json -Depth 8|Set-Content "$assets/blockstates/oak_newel_post.json"
@{model=@{type='minecraft:model';model='atouchofclass:item/oak_newel_post'}}|ConvertTo-Json -Depth 5|Set-Content "$assets/items/oak_newel_post.json"
$table=$tables-join ",`n"
@"
package com.digitaldownpour.atouchofclass.blocks;
import net.minecraft.core.Direction;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.state.properties.DoubleBlockHalf;
import net.minecraft.world.phys.shapes.*;
// Generated by tools/generate-newel-post.ps1; both block halves use model coordinates.
final class NewelPostGeometry {
    private static final double[][][] BOXES={
$table
    };
    private static final VoxelShape[][] SHAPES=new VoxelShape[2][4];
    static {
        for(int h=0;h<2;h++)for(int r=0;r<4;r++) {
            VoxelShape shape=Shapes.empty();
            for(double[] b:BOXES[h]) {
                double x0=b[0],z0=b[2],x1=b[3],z1=b[5];
                for(int i=0;i<r;i++){double a=16-z1,c=16-z0;z0=x0;z1=x1;x0=a;x1=c;}
                shape=Shapes.or(shape,Block.box(x0,b[1],z0,x1,b[4],z1));
            }
            SHAPES[h][r]=shape.optimize();
        }
    }
    static VoxelShape shape(Direction facing,DoubleBlockHalf half) {
        return SHAPES[half==DoubleBlockHalf.LOWER?0:1][switch(facing){case EAST->1;case SOUTH->2;case WEST->3;default->0;}];
    }
}
"@|Set-Content "$root/src/main/java/com/digitaldownpour/atouchofclass/blocks/NewelPostGeometry.java"
